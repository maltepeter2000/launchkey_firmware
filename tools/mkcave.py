#!/usr/bin/env python3
"""Turn the linked cfw ELF + cfw/hooks.txt into patch files for apply_patches.py.

Usage: mkcave.py cfw.elf hooks.txt stock.bin <code.patch> <hooks.patch>

  code.patch   the ELF's .text (code + rodata) as free-space lines ('-' = must be 0xFF / past end)
  hooks.patch  one Thumb-2 BL or B.W per hook line, original bytes taken from hooks.txt and
               checked against stock.bin here already

hooks.txt line: <address> bl|b.w <symbol> <original bytes hex>   [# comment]
"""
import argparse
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile

BASE = 0x08008000
LINE = 32


def thumb_branch(src: int, dst: int, link: bool) -> bytes:
    """Encode BL (T1) or B.W (T4) at src jumping to dst; returns 4 bytes little-endian halfwords."""
    off = (dst & ~1) - (src + 4)
    if off & 1 or not -(1 << 24) <= off < (1 << 24):
        raise ValueError(f"branch 0x{src:08x} -> 0x{dst:08x} out of range or misaligned")
    s = off >> 24 & 1
    j1 = (~(off >> 23) ^ s) & 1
    j2 = (~(off >> 22) ^ s) & 1
    hi = 0xF000 | s << 10 | off >> 12 & 0x3FF
    lo = (0xD000 if link else 0x9000) | j1 << 13 | j2 << 11 | off >> 1 & 0x7FF
    return hi.to_bytes(2, "little") + lo.to_bytes(2, "little")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("elf", type=Path)
    ap.add_argument("hooks", type=Path)
    ap.add_argument("stock", type=Path)
    ap.add_argument("code_patch", type=Path)
    ap.add_argument("hooks_patch", type=Path)
    a = ap.parse_args()

    with a.elf.open("rb") as f:
        elf = ELFFile(f)
        text = elf.get_section_by_name(".text")
        start, code = text["sh_addr"], text.data()
        syms = {s.name: s["st_value"] for s in elf.get_section_by_name(".symtab").iter_symbols() if s.name}
        bss = elf.get_section_by_name(".bss")
        ram = bss["sh_size"] if bss else 0

    lines = [f"# generated by tools/mkcave.py from {a.elf.name}: cfw code, {len(code)} bytes @ 0x{start:08x}"]
    for off in range(0, len(code), LINE):
        lines.append(f"0x{start + off:08x}  -  {code[off:off + LINE].hex()}")
    a.code_patch.write_text("# cfw code (Turing Machine mode, CC pages)\n" + "\n".join(lines) + "\n")

    stock = a.stock.read_bytes()
    out = ["# cfw hooks into the stock firmware",
           f"# generated by tools/mkcave.py from {a.hooks.name}"]
    for lineno, raw in enumerate(a.hooks.read_text().splitlines(), 1):
        code_part, _, comment = raw.partition("#")
        f = code_part.split()
        if not f:
            continue
        if len(f) != 4 or f[1] not in ("bl", "b.w"):
            sys.exit(f"{a.hooks}:{lineno}: expected '<addr> bl|b.w <symbol> <orig hex>'")
        addr, kind, sym, orig = int(f[0], 16), f[1], f[2], bytes.fromhex(f[3])
        if sym not in syms:
            sys.exit(f"{a.hooks}:{lineno}: symbol '{sym}' not in {a.elf}")
        cur = stock[addr - BASE:addr - BASE + 4]
        if cur != orig:
            sys.exit(f"{a.hooks}:{lineno}: 0x{addr:08x} is {cur.hex()}, hooks.txt expects {orig.hex()}")
        new = thumb_branch(addr, syms[sym], kind == "bl")
        out.append(f"0x{addr:08x}  {orig.hex()}  {new.hex()}   # {kind} {sym}  {comment.strip()}".rstrip())
    a.hooks_patch.write_text("\n".join(out) + "\n")
    print(f"cfw: {len(code)} bytes code @ 0x{start:08x}, {ram} bytes RAM, "
          f"{len(out) - 2} hooks -> {a.code_patch}, {a.hooks_patch}")


if __name__ == "__main__":
    main()
